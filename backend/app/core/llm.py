from backend.app.core.config import Settings, get_settings

FakeResponseFactory = Callable[
    [type[BaseModel], str, str, int],
    BaseModel | Mapping[str, object],
]

_DEFAULT_FAKE_RESPONSES: dict[str, dict[str, object]] = {
    "Classification": {
        "category": "other",
        "summary": "Support request received.",
        "confidence": 0.5,
        "injection_detected": False,
    },
    "SeverityAssessment": {
        "severity": "medium",
        "reason": "The request needs review but has no confirmed critical impact.",
    },
    "DiagnosisDraft": {
        "probable_causes": ["The available information does not confirm a root cause."],
        "steps": [
            "Confirm the affected account and reproduce the reported behavior.",
            "Compare the result with the relevant support guidance.",
        ],
    },
    "ResolutionDraft": {
        "summary": "The support request is under review.",
        "customer_reply": "We are reviewing the issue and will share verified next steps.",
        "internal_notes": "The draft was generated by the offline fake provider.",
    },
    "EscalationDecision": {
        "escalation_required": False,
        "team": None,
        "reason": "No additional escalation signal was identified.",
        "confidence": 0.5,
        "policy_rule": None,
    },
}


@dataclass(frozen=True, slots=True)
class StructuredCallResult[ModelT: BaseModel]:
    output: ModelT
    usage: dict[str, int]
    duration_ms: float
    estimated_cost: float | None


class FakeLLM:
    """Deterministic structured-output provider for offline use and tests."""

    def __init__(
        self,
        responses: Mapping[
            type[BaseModel],
            BaseModel | Mapping[str, object] | FakeResponseFactory,
        ]
        | None = None,
    ) -> None:
        self.responses = dict(responses or {})
        self.calls: list[tuple[str, str, str]] = []

    async def complete(
        self,
        schema: type[BaseModel],
        *,
        system_prompt: str,
        user_prompt: str,
    ) -> tuple[object, dict[str, int]]:
        self.calls.append((schema.__name__, system_prompt, user_prompt))
        call_number = sum(name == schema.__name__ for name, _, _ in self.calls)
        response = self.responses.get(schema)
        if response is None:
            response = _DEFAULT_FAKE_RESPONSES.get(schema.__name__)
        if response is None:
            raise ValueError(f"No offline fake response configured for {schema.__name__}")
        if callable(response):
            response = response(schema, system_prompt, user_prompt, call_number)

        encoded_prompt = system_prompt + user_prompt
        encoded_output = (
            response.model_dump_json()
            if isinstance(response, BaseModel)
            else json.dumps(response, separators=(",", ":"), default=str)
        )
        usage = {
            "input_tokens": _estimate_tokens(encoded_prompt),
            "output_tokens": _estimate_tokens(encoded_output),
        }
        return response, usage


def get_llm(settings: Settings | None = None) -> FakeLLM | BaseChatModel:
    settings = settings or get_settings()
    if settings.llm_provider.casefold() == "fake":
        return FakeLLM()

    api_key = (
        settings.llm_api_key.get_secret_value()
        if settings.llm_api_key is not None
        else None
    )
    if api_key is None:
        raise ValueError(f"LLM_API_KEY is required for provider {settings.llm_provider!r}")
    return init_chat_model(
        settings.llm_model,
        model_provider=settings.llm_provider,
        api_key=api_key,
    )


async def call_structured[ModelT: BaseModel](
    schema: type[ModelT],
    *,
    system_prompt: str,
    user_prompt: str,
    llm: FakeLLM | BaseChatModel | None = None,
    retries: int = 1,
) -> StructuredCallResult[ModelT]:
    """Call a provider, validate its Pydantic output, and report usage and latency."""
    if retries < 0 or retries > 3:
        raise ValueError("retries must be between zero and three")
    provider = llm or get_llm()
    started_at = perf_counter()
    total_usage = {"input_tokens": 0, "output_tokens": 0}
    last_error: ValidationError | None = None

    for attempt in range(retries + 1):
        retry_prompt = user_prompt
        if attempt:
            retry_prompt += (
                "\n\nThe prior result did not match the required schema. "
                "Return a corrected result that satisfies the schema."
            )

        if isinstance(provider, FakeLLM):
            raw_output, usage = await provider.complete(
                schema,
                system_prompt=system_prompt,
                user_prompt=retry_prompt,
            )
        else:
            response = await provider.with_structured_output(
                schema,
                include_raw=True,
            ).ainvoke(
                [
                    SystemMessage(content=system_prompt),
                    HumanMessage(content=retry_prompt),
                ]
            )
            if not isinstance(response, Mapping):
                raise TypeError("Structured LLM response must include parsed and raw values")
            parsing_error = response.get("parsing_error")
            if parsing_error is not None:
                raise ValueError("The LLM provider could not parse its structured response")
            raw_output = response.get("parsed")
            raw_message = response.get("raw")
            usage_metadata = getattr(raw_message, "usage_metadata", None)
            usage = _normalize_usage(usage_metadata)

        total_usage["input_tokens"] += usage.get(
            "input_tokens",
            _estimate_tokens(system_prompt + retry_prompt),
        )
        total_usage["output_tokens"] += usage.get(
            "output_tokens",
            _estimate_tokens(str(raw_output)),
        )
        try:
            output = schema.model_validate(raw_output)
        except ValidationError as error:
            last_error = error
            if attempt == retries:
                raise
            continue

        duration_ms = (perf_counter() - started_at) * 1000
        return StructuredCallResult(
            output=output,
            usage=total_usage,
            duration_ms=duration_ms,
            estimated_cost=0.0 if isinstance(provider, FakeLLM) else None,
        )

    if last_error is not None:
        raise last_error
    raise RuntimeError("Structured call ended without an output")


def _estimate_tokens(text: str) -> int:
    return max(1, math.ceil(len(text) / 4))


def _normalize_usage(value: object) -> dict[str, int]:
    if not isinstance(value, Mapping):
        return {"input_tokens": 0, "output_tokens": 0}
    normalized: dict[str, int] = {}
    for key in ("input_tokens", "output_tokens"):
        token_count = value.get(key, 0)
        normalized[key] = (
            token_count
            if isinstance(token_count, int) and not isinstance(token_count, bool)
            else 0
        )
    return normalized


